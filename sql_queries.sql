-- Query 10: Customers Above Average Spending

SELECT customer_name,
       total_spending
FROM (
    SELECT c.customer_name,
           SUM(oi.quantity * p.price) AS total_spending
    FROM customers AS c
    JOIN orders AS o
        ON c.customer_id = o.customer_id
    JOIN order_items AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
    WHERE o.status = 'delivered'
    GROUP BY c.customer_name
) AS customer_spending
WHERE total_spending > (
    SELECT AVG(total_spending)
    FROM (
        SELECT c2.customer_id,
               SUM(oi2.quantity * p2.price) AS total_spending
        FROM customers AS c2
        JOIN orders AS o2
            ON c2.customer_id = o2.customer_id
        JOIN order_items AS oi2
            ON o2.order_id = oi2.order_id
        JOIN products AS p2
            ON oi2.product_id = p2.product_id
        WHERE o2.status = 'delivered'
        GROUP BY c2.customer_id
    ) AS spending_per_customer
);

Business Insight:
This query identifies customers whose total spending is above the average customer spending, helping the business identify high-value customers.


-- Query 11: Top 2 Products in Each Category

SELECT category,
       product_name,
       revenue_generated,
       revenue_rank
FROM (
    SELECT p.category,
           p.product_name,
           SUM(oi.quantity * p.price) AS revenue_generated,
           DENSE_RANK() OVER (
               PARTITION BY p.category
               ORDER BY SUM(oi.quantity * p.price) DESC
           ) AS revenue_rank
    FROM products AS p
    JOIN order_items AS oi
        ON p.product_id = oi.product_id
    JOIN orders AS o
        ON oi.order_id = o.order_id
    WHERE o.status = 'delivered'
    GROUP BY p.category, p.product_name
) AS ranked_products
WHERE revenue_rank <= 2;

Business Insight:
This query identifies the top two revenue-generating products within each category, helping the business understand the strongest products across different categories.


-- Query 12: Highest-Spending Customer in Each City

SELECT city,
       customer_name,
       total_spending
FROM (
    SELECT c.city,
           c.customer_name,
           SUM(oi.quantity * p.price) AS total_spending,
           DENSE_RANK() OVER (
               PARTITION BY c.city
               ORDER BY SUM(oi.quantity * p.price) DESC
           ) AS spending_rank
    FROM customers AS c
    JOIN orders AS o
        ON c.customer_id = o.customer_id
    JOIN order_items AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
    WHERE o.status = 'delivered'
    GROUP BY c.city, c.customer_name
) AS ranked_customers
WHERE spending_rank = 1;

Business Insight:
This query identifies the highest-spending customers in each city, helping the business understand its most valuable customers across different locations.

