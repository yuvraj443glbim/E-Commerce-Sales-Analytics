-- Query 1: Total Revenue from Delivered Orders

SELECT SUM(oi.quantity * p.price) AS total_revenue
FROM orders AS o
JOIN order_items AS oi
    ON o.order_id = oi.order_id
JOIN products AS p
    ON oi.product_id = p.product_id
WHERE o.status = 'delivered';

Business insight

This query calculates the total revenue generated from successfully delivered orders, providing a high-level measure of the business's realized sales revenue.


-- Query 2: Revenue by Product Category

SELECT p.category,
       SUM(oi.quantity * p.price) AS revenue_generated
FROM products AS p
JOIN order_items AS oi
    ON p.product_id = oi.product_id
JOIN orders AS o
    ON oi.order_id = o.order_id
WHERE o.status = 'delivered'
GROUP BY p.category
ORDER BY revenue_generated DESC;

Business Insight:
This query compares revenue generated by each product category and helps identify the categories contributing the most to overall sales.


