-- Query 6: Repeat Customers

SELECT c.customer_name,
       COUNT(o.order_id) AS total_orders
FROM customers AS c
JOIN orders AS o
    ON c.customer_id = o.customer_id
WHERE o.status = 'delivered'
GROUP BY c.customer_name
HAVING COUNT(o.order_id) >= 2;

Business Insight:
This query identifies customers who have made at least two delivered orders, helping measure repeat customer activity.


-- Query 7: Average Order Value

SELECT AVG(total_revenue) AS average_order_value
FROM (
    SELECT o.order_id,
           SUM(oi.quantity * p.price) AS total_revenue
    FROM orders AS o
    JOIN order_items AS oi
        ON o.order_id = oi.order_id
    JOIN products AS p
        ON oi.product_id = p.product_id
    WHERE o.status = 'delivered'
    GROUP BY o.order_id
) AS order_placed;

Business Insight:
This query calculates the average value of a delivered order, helping measure the typical amount customers spend per order.


